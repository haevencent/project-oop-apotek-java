public class Obat {
    public String idObat;
    public String namaObat;
    public double harga;
    public boolean butuhResep;

    public Obat(String idObat, String namaObat, double harga, boolean butuhResep) {
        this.idObat = idObat;
        this.namaObat = namaObat;
        this.harga = harga;
        this.butuhResep = butuhResep;
    }
}
